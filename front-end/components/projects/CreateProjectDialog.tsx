"use client";

import { useState } from "react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
  DialogFooter,
} from "@/components/ui/dialog";
import {
  createProject,
  validateDescription,
  validateProjectSlug,
  type Project,
} from "@/lib/api";
import { Textarea } from "@/components/ui/textarea";
import { RefreshDouble } from "iconoir-react";

type Props = {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onCreated: (p: Project) => void;
};

export function CreateProjectDialog({ open, onOpenChange, onCreated }: Props) {
  const [name, setName] = useState("");
  const [slug, setSlug] = useState("");
  const [description, setDescription] = useState("");
  const [slugError, setSlugError] = useState<string | null>(null);
  const [formError, setFormError] = useState<string | null>(null);
  const [creating, setCreating] = useState(false);

  function reset() {
    setName("");
    setSlug("");
    setDescription("");
    setSlugError(null);
    setFormError(null);
  }

  function handleOpenChange(o: boolean) {
    onOpenChange(o);
    if (!o) reset();
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!name.trim()) {
      setFormError("Name is required");
      return;
    }
    const sErr = validateProjectSlug(slug.trim());
    if (sErr) {
      setSlugError(sErr);
      return;
    }
    const descError = validateDescription(description.trim());
    if (descError) {
      setFormError(descError);
      return;
    }
    setSlugError(null);
    setFormError(null);
    setCreating(true);
    try {
      const p = await createProject({
        name: name.trim(),
        slug: slug.trim() || undefined,
        description: description.trim(),
      });
      onCreated(p);
      handleOpenChange(false);
    } catch (err) {
      const msg = err instanceof Error ? err.message : "Failed to create project";
      if (msg.toLowerCase().includes("slug") || msg.toLowerCase().includes("name")) {
        setFormError(msg);
      } else {
        setFormError(msg);
      }
    } finally {
      setCreating(false);
    }
  }

  return (
    <Dialog open={open} onOpenChange={handleOpenChange}>
      <DialogContent className="sm:max-w-[440px]">
        <DialogHeader>
          <DialogTitle>Create project</DialogTitle>
          <DialogDescription>
            Create a project. You will become its owner and can add members.
          </DialogDescription>
        </DialogHeader>
        <form onSubmit={handleSubmit} className="space-y-4">
          <div className="space-y-2">
            <Label htmlFor="project-name">Name</Label>
            <Input
              id="project-name"
              placeholder="My blog"
              value={name}
              onChange={(e) => setName(e.target.value)}
            />
          </div>
          <div className="space-y-2">
            <Label htmlFor="project-slug">Slug <span className="font-normal text-muted-foreground">(optional)</span></Label>
            <Input
              id="project-slug"
              placeholder="project-strawberry-7k2q"
              value={slug}
              onChange={(e) => {
                setSlug(e.target.value);
                if (slugError) setSlugError(null);
              }}
              aria-invalid={!!slugError}
            />
            {slugError ? (
              <p className="text-xs text-destructive">{slugError}</p>
            ) : (
              <p className="text-xs text-muted-foreground">3-40 chars, lowercase letters, numbers and hyphens. Empty = autogenerated</p>
            )}
          </div>
          <div className="space-y-2">
            <Label htmlFor="project-description">Description <span className="font-normal text-muted-foreground">(optional)</span></Label>
            <Textarea
              id="project-description"
              placeholder="What is this project for?"
              value={description}
              onChange={(e) => setDescription(e.target.value)}
              maxLength={1000}
              rows={3}
            />
            <p className="text-xs text-muted-foreground">{description.trim().length}/1000</p>
          </div>

          {formError && <div className="rounded-md border border-destructive/30 bg-destructive/10 px-3 py-2 text-sm text-destructive">{formError}</div>}
          <DialogFooter>
            <Button type="button" variant="outline" onClick={() => handleOpenChange(false)} disabled={creating}>
              Cancel
            </Button>
            <Button type="submit" disabled={creating}>
              {creating ? (
                <>
                  <RefreshDouble className="h-4 w-4 animate-spin" />
                  Creating...
                </>
              ) : (
                "Create"
              )}
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  );
}
